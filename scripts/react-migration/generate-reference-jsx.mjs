const executablePath = await findChrome();
const browser = await chromium.launch({ executablePath, headless: true });
let chromeSnapshot;

try {
	await Promise.all([
		mkdir(outputRoot, { recursive: true }),
		mkdir(componentRoot, { recursive: true }),
	]);

	for (const pageDefinition of pages) {
		const sourcePath = path.join(sourceRoot, pageDefinition.referencePath);
		const sourceHtml = await readFile(sourcePath, "utf8");
		const page = await browser.newPage();

		try {
			await page.setContent(sourceHtml, { waitUntil: "domcontentloaded" });
			const documentSnapshot = await page.evaluate(() => ({
				bodyClassName: document.body.className,
				bodyHtml: document.body.innerHTML,
				bodyItemType: document.body.getAttribute("itemtype"),
			}));

			if (pageDefinition.referencePath === "index.html") {
				chromeSnapshot = documentSnapshot;
			}

			const output = renderComponent(pageDefinition, documentSnapshot);
			await writeFile(path.join(outputRoot, pageDefinition.outputPath), output);
			console.log(
				`Generated ${path.relative(repositoryRoot, path.join(outputRoot, pageDefinition.outputPath))}`,
			);
		} finally {
			await page.close();
		}
	}

	if (!chromeSnapshot)
		throw new Error("Home reference chrome was not captured.");

	const chromeOutputPath = path.join(componentRoot, "site-chrome.tsx");
	await writeFile(chromeOutputPath, renderChromeComponent(chromeSnapshot));
	console.log(`Generated ${path.relative(repositoryRoot, chromeOutputPath)}`);
} finally {
	await browser.close();
}

function renderComponent(pageDefinition, documentSnapshot) {
	let rewrittenHtml = rewriteReferenceUrls(
		documentSnapshot.bodyHtml,
		pageDefinition.referencePath,
	);
	if (pageDefinition.referencePath === "index.html") {
		rewrittenHtml = replaceHomeFocusArea(rewrittenHtml);
	}
	const usesCustomElement = rewrittenHtml.includes("<ss3-loader");
	const currentPage =
		pageDefinition.referencePath === "about/index.html" ? "about" : "home";
	const jsx = htmlToJsx(
		replaceElement(
			replaceElement(
				rewrittenHtml,
				"header",
				`<SiteHeader currentPage="${currentPage}" />`,
			),
			"footer",
			"<SiteFooter />",
		),
	);
	const imports = usesCustomElement
		? 'import { createElement } from "react";\n'
		: "";
	const chromeImport =
		'import { SiteFooter, SiteHeader } from "../_components/site-chrome";\n\n';
	const pageSectionImport =
		pageDefinition.referencePath === "index.html"
			? 'import { FocusAreaSection } from "../_components/home-sections";\n'
			: "";
	const bodyItemType = documentSnapshot.bodyItemType
		? ` itemType=${JSON.stringify(documentSnapshot.bodyItemType)}`
		: "";

	return `// biome-ignore-all lint: This file is a mechanical JSX checkpoint generated from the verified Tailwind reference.\n// biome-ignore-all format: Formatting generated JSX can change significant HTML whitespace.\n${imports}${pageSectionImport}${chromeImport}// Generated by scripts/react-migration/generate-reference-jsx.mjs.\n\nconst bodyClassName = ${JSON.stringify(documentSnapshot.bodyClassName)};\n\nexport function ${pageDefinition.componentName}() {\n\treturn (\n\t\t<div className={bodyClassName} data-tailwind-migration-document=\"body\" itemScope${bodyItemType}>\n${jsx}\n\t\t</div>\n\t);\n}\n`;
}

