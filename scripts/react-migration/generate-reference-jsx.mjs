function extractElementByDataNode(html, nodeId) {
	const openingTagPattern = new RegExp(
		`<div\\b[^>]*\\bdata-node="${nodeId}"[^>]*>`,
	);
	const openingTag = openingTagPattern.exec(html);
	if (!openingTag) throw new Error(`Could not find data-node ${nodeId}.`);

	const tagPattern = /<\/?div\b[^>]*>/g;
	tagPattern.lastIndex = openingTag.index;
	let depth = 0;
	let tag;

	while ((tag = tagPattern.exec(html))) {
		depth += tag[0].startsWith("</") ? -1 : 1;
		if (depth === 0) return html.slice(openingTag.index, tagPattern.lastIndex);
	}

	throw new Error(`Could not find closing tag for data-node ${nodeId}.`);
}

function renderChromeComponent(documentSnapshot) {
	const rewrittenHtml = rewriteReferenceUrls(
		documentSnapshot.bodyHtml,
		"index.html",
	);
	const headerHtml = stripChromeIdentityClasses(
		extractElement(rewrittenHtml, "header"),
	);
	const footerHtml = stripChromeIdentityClasses(
		extractElement(rewrittenHtml, "footer"),
	);
	const navigationHtml = extractElement(headerHtml, "nav");
	const headerJsx = htmlToJsx(
		headerHtml.replace(
			navigationHtml,
			"<SiteNavigation currentPage={currentPage} />",
		),
	);
	const navigationJsx = addCurrentPageState(htmlToJsx(navigationHtml));
	const footerJsx = htmlToJsx(footerHtml);

	return `// biome-ignore-all lint: This file preserves the verified chrome markup while its implementation is migrated.\n// biome-ignore-all format: Formatting reference JSX can change significant HTML whitespace.\n// Generated by scripts/react-migration/generate-reference-jsx.mjs.\n\nexport type SiteChromePage = "home" | "about";\n\nexport function SiteHeader({ currentPage }: { currentPage: SiteChromePage }) {\n\treturn (\n${headerJsx}\n\t);\n}\n\nfunction SiteNavigation({ currentPage }: { currentPage: SiteChromePage }) {\n\treturn (\n${navigationJsx}\n\t);\n}\n\nexport function SiteFooter() {\n\treturn (\n${footerJsx}\n\t);\n}\n`;
}

function extractElement(html, tagName) {
	const start = html.indexOf(`<${tagName}`);
	const closingTag = `</${tagName}>`;
	const end = html.indexOf(closingTag, start);

	if (start === -1 || end === -1) {
		throw new Error(`Could not find <${tagName}> in the reference document.`);
	}

	return html.slice(start, end + closingTag.length);
}

function replaceElement(html, tagName, replacement) {
	return html.replace(extractElement(html, tagName), replacement);
}

function addCurrentPageState(headerJsx) {
	return headerJsx
		.replace(
			'<li id="menu-item-48">',
			'<li id="menu-item-48" className={currentPage === "about" ? "current-menu-item" : undefined}>',
		)
		.replace(
		'href="/tailwind-migration/about"><span>About DFN',
		'href="/tailwind-migration/about" aria-current={currentPage === "about" ? "page" : undefined}><span>About DFN',
		);
}

function stripChromeIdentityClasses(html) {
	return html.replace(/\sclass="([^"]*)"/g, (_match, className) => {
		const classes = className
			.split(/\s+/)
			.filter(Boolean)
			.filter((name) => !isBuilderIdentityClass(name));

		return classes.length > 0 ? ` class="${classes.join(" ")}"` : "";
	});
}

function isBuilderIdentityClass(className) {
	return (
		className.startsWith("fl-node-") ||
		(className.startsWith("fl-") && !requiredFlClasses.has(className)) ||
		(className.startsWith("pp-") && !requiredPowerPackClasses.has(className)) ||
		className.startsWith("wp-") ||
		className === "menu-item" ||
		className.startsWith("menu-item-") ||
		className === "page_item" ||
		className.startsWith("page-item-") ||
		className === "current_page_item" ||
		className === "hamburger" ||
		className === "size-full" ||
		/^[ps]\d+$/.test(className)
	);
}

function rewriteReferenceUrls(html, referencePath) {
	const isAboutPage = referencePath === "about/index.html";

	return html
		.replace(
			/(["'(,\s])(?:\.\.\/)?(assets|wp-content)\//g,
			`$1${assetBasePath}/$2/`,
		)
		.replace(
			/href=(["'])about\/index\.html(["'#])/g,
			"href=$1/tailwind-migration/about$2",
		)
		.replace(
			/href=(["'])\.\.\/index\.html(["'#])/g,
			"href=$1/tailwind-migration$2",
		)
		.replace(
			/href=(["'])index\.html(#fl-main-content)?(["'])/g,
			(_match, quote, hash) =>
				`href=${quote}${isAboutPage ? "/tailwind-migration/about" : "/tailwind-migration"}${hash ?? ""}${quote}`,
		);
}

function htmlToJsx(html) {
	let jsx = html
		.replace(/<!--[\s\S]*?-->/g, "")
		.replace(/\sonclick=\"\"/g, "")
		.replace(/\sitemscope=(?:\"itemscope\"|\"\")/g, " itemScope")
		.replace(/\srequired=\"\"/g, " required")
		.replace(/\stabindex=\"(-?\d+)\"/g, " tabIndex={$1}");

	for (const [htmlName, jsxName] of attributeNames) {
		jsx = jsx.replace(new RegExp(`\\b${htmlName}=`, "g"), `${jsxName}=`);
	}

	jsx = jsx
		.replace(
			new RegExp(`<(${voidElements})(\\b[^>]*?)(?<!\\/)>`, "gi"),
			"<$1$2 />",
		)
		.replace(/<ss3-loader><\/ss3-loader>/g, '{createElement("ss3-loader")}');

	return jsx;
}

async function findChrome() {
	const candidates = [
		process.env.STYLE_PARITY_CHROME_PATH,
		"/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
		"/usr/bin/google-chrome",
		"/usr/bin/chromium",
		"/usr/bin/chromium-browser",
	].filter(Boolean);

	for (const candidate of candidates) {
		try {
			await access(candidate);
			return candidate;
		} catch {
			// Try the next known Chrome location.
		}
	}

	throw new Error(
		"Chrome was not found. Set STYLE_PARITY_CHROME_PATH to its executable.",
	);
}
