#!/usr/bin/env node

import { access, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { chromium } from "playwright-core";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, "../..");
const sourceRoot = path.join(
	repositoryRoot,
	"docs/references/tailwind-migration/site",
);
const outputRoot = path.join(
	repositoryRoot,
	"apps/web/src/app/tailwind-migration/_generated",
);
const assetBasePath = "/tailwind-migration/reference";

const pages = [
	{
		componentName: "HomeTailwindReference",
		outputPath: "home-reference.tsx",
		referencePath: "index.html",
	},
	{
		componentName: "AboutTailwindReference",
		outputPath: "about-reference.tsx",
		referencePath: "about/index.html",
	},
];

const attributeNames = new Map([
	["class", "className"],
	["crossorigin", "crossOrigin"],
	["fetchpriority", "fetchPriority"],
	["for", "htmlFor"],
	["itemprop", "itemProp"],
	["itemscope", "itemScope"],
	["itemtype", "itemType"],
	["srcset", "srcSet"],
	["tabindex", "tabIndex"],
]);
const voidElements =
	"area|base|br|col|embed|hr|img|input|link|meta|param|source|track|wbr";

const executablePath = await findChrome();
const browser = await chromium.launch({ executablePath, headless: true });

try {
	await mkdir(outputRoot, { recursive: true });

	for (const pageDefinition of pages) {
		const sourcePath = path.join(sourceRoot, pageDefinition.referencePath);
		const sourceHtml = await readFile(sourcePath, "utf8");
		const page = await browser.newPage();

		try {
			await page.setContent(sourceHtml, { waitUntil: "domcontentloaded" });
			const documentSnapshot = await page.evaluate(() => ({
				bodyClassName: document.body.className,
				bodyHtml: document.body.innerHTML,
				bodyItemType: document.body.getAttribute("itemtype"),
			}));

			const output = renderComponent(pageDefinition, documentSnapshot);
			await writeFile(path.join(outputRoot, pageDefinition.outputPath), output);
			console.log(
				`Generated ${path.relative(repositoryRoot, path.join(outputRoot, pageDefinition.outputPath))}`,
			);
		} finally {
			await page.close();
		}
	}
} finally {
	await browser.close();
}

function renderComponent(pageDefinition, documentSnapshot) {
	const usesCustomElement = documentSnapshot.bodyHtml.includes("<ss3-loader");
	const jsx = htmlToJsx(
		rewriteReferenceUrls(
			documentSnapshot.bodyHtml,
			pageDefinition.referencePath,
		),
	);
	const imports = usesCustomElement
		? 'import { createElement } from "react";\n\n'
		: "";
	const bodyItemType = documentSnapshot.bodyItemType
		? ` itemType=${JSON.stringify(documentSnapshot.bodyItemType)}`
		: "";

	return `// biome-ignore-all lint: This file is a mechanical JSX checkpoint generated from the verified Tailwind reference.\n// biome-ignore-all format: Formatting generated JSX can change significant HTML whitespace.\n${imports}// Generated by scripts/react-migration/generate-reference-jsx.mjs.\n\nconst bodyClassName = ${JSON.stringify(documentSnapshot.bodyClassName)};\n\nexport function ${pageDefinition.componentName}() {\n\treturn (\n\t\t<div className={bodyClassName} data-tailwind-migration-document=\"body\" itemScope${bodyItemType}>\n${jsx}\n\t\t</div>\n\t);\n}\n`;
}

function rewriteReferenceUrls(html, referencePath) {
	const isAboutPage = referencePath === "about/index.html";

	return html
		.replace(
			/(["'(,\s])(?:\.\.\/)?(assets|wp-content)\//g,
			`$1${assetBasePath}/$2/`,
		)
		.replace(
			/href=(["'])about\/index\.html(["'#])/g,
			"href=$1/tailwind-migration/about$2",
		)
		.replace(
			/href=(["'])\.\.\/index\.html(["'#])/g,
			"href=$1/tailwind-migration$2",
		)
		.replace(
			/href=(["'])index\.html(#fl-main-content)?(["'])/g,
			(_match, quote, hash) =>
				`href=${quote}${isAboutPage ? "/tailwind-migration/about" : "/tailwind-migration"}${hash ?? ""}${quote}`,
		);
}

function htmlToJsx(html) {
	let jsx = html
		.replace(/<!--[\s\S]*?-->/g, "")
		.replace(/\sonclick=\"\"/g, "")
		.replace(/\sitemscope=(?:\"itemscope\"|\"\")/g, " itemScope")
		.replace(/\srequired=\"\"/g, " required")
		.replace(/\stabindex=\"(-?\d+)\"/g, " tabIndex={$1}");

	for (const [htmlName, jsxName] of attributeNames) {
		jsx = jsx.replace(new RegExp(`\\b${htmlName}=`, "g"), `${jsxName}=`);
	}

	jsx = jsx
		.replace(
			new RegExp(`<(${voidElements})(\\b[^>]*?)(?<!\\/)>`, "gi"),
			"<$1$2 />",
		)
		.replace(/<ss3-loader><\/ss3-loader>/g, '{createElement("ss3-loader")}');

	return jsx;
}

async function findChrome() {
	const candidates = [
		process.env.STYLE_PARITY_CHROME_PATH,
		"/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
		"/usr/bin/google-chrome",
		"/usr/bin/chromium",
		"/usr/bin/chromium-browser",
	].filter(Boolean);

	for (const candidate of candidates) {
		try {
			await access(candidate);
			return candidate;
		} catch {
			// Try the next known Chrome location.
		}
	}

	throw new Error(
		"Chrome was not found. Set STYLE_PARITY_CHROME_PATH to its executable.",
	);
}
